import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// JSON remains the source of truth; generated literals preserve interpolation types.
const root = resolve("src/infrastructure/i18n/locales/en");
const messages = {};

function flatten(value, prefix) {
  for (const [key, entry] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;

    if (typeof entry === "string")
      messages[path.replace(/_(zero|one|two|few|many|other)$/, "")] = entry;
    else flatten(entry, path);
  }
}

for (const file of readdirSync(root)
  .filter((name) => name.endsWith(".json"))
  .sort()) {
  flatten(
    JSON.parse(readFileSync(resolve(root, file), "utf8")),
    `${file.slice(0, -5)}:`,
  );
}

const output = `// Generated by pnpm i18n:types. Do not edit.\nexport type AppMessages = {\n${Object.entries(
  messages,
)
  .map(
    ([key, value]) =>
      `  ${JSON.stringify(key.replace(":.", ":"))}: ${JSON.stringify(value)};`,
  )
  .join("\n")}\n};\n`;

const target = resolve("src/shared/i18n/app-messages.ts");

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error("Translation types are stale. Run pnpm i18n:types.");
} else writeFileSync(target, output);
