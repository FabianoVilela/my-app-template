import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// JSON remains the source of truth; generated literals preserve interpolation types.
const HEADER = "// Generated by pnpm i18n:types. Do not edit.\n";
const localesRoot = resolve("src/infrastructure/i18n/locales");
const messages = {};

function flatten(value, prefix) {
  for (const [key, entry] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;

    if (typeof entry === "string")
      messages[path.replace(/_(zero|one|two|few|many|other)$/, "")] = entry;
    else flatten(entry, path);
  }
}

const camelCase = (value) =>
  value.replace(/[-_.]([a-z0-9])/gi, (_, next) => next.toUpperCase());

// English is the reference catalog: its files define the namespaces.
const namespaces = readdirSync(resolve(localesRoot, "en"))
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.slice(0, -5))
  .sort();

// Directories are lowercase locale tags (pt-br); keys use BCP 47 (pt-BR).
const locales = readdirSync(localesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map(({ name }) => ({
    directory: name,
    locale: Intl.getCanonicalLocales(name)[0],
  }))
  .sort((a, b) => a.directory.localeCompare(b.directory));

for (const namespace of namespaces) {
  flatten(
    JSON.parse(
      readFileSync(resolve(localesRoot, "en", `${namespace}.json`), "utf8"),
    ),
    `${namespace}:`,
  );
}

const messagesOutput = `${HEADER}export type AppMessages = {\n${Object.entries(
  messages,
)
  .map(
    ([key, value]) =>
      `  ${JSON.stringify(key.replace(":.", ":"))}: ${JSON.stringify(value)};`,
  )
  .join("\n")}\n};\n`;

const identifier = (directory, namespace) =>
  camelCase(`${directory}-${namespace}`);
const property = (name) =>
  /^[a-zA-Z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);

// Match Biome's formatting: one line while it fits in 80 columns.
const namespaceList = namespaces.map((namespace) => JSON.stringify(namespace));
const inlineNamespaces = `export const NAMESPACES = [${namespaceList.join(", ")}] as const;`;
const namespacesOutput =
  inlineNamespaces.length <= 80
    ? inlineNamespaces
    : `export const NAMESPACES = [\n${namespaceList.map((name) => `  ${name},`).join("\n")}\n] as const;`;

const resourcesOutput = `${HEADER}import type { AppLocale } from "@/shared/i18n/contracts";
${locales
  .flatMap(({ directory }) =>
    namespaces.map(
      (namespace) =>
        `import ${identifier(directory, namespace)} from "./locales/${directory}/${namespace}.json";`,
    ),
  )
  .join("\n")}

${namespacesOutput}

// satisfies fails type checking when APP_LOCALES and locale directories differ.
export const resources = {
${locales
  .map(
    ({ directory, locale }) =>
      `  ${property(locale)}: {\n${namespaces
        .map(
          (namespace) =>
            `    ${property(namespace)}: ${identifier(directory, namespace)},`,
        )
        .join("\n")}\n  },`,
  )
  .join("\n")}
} satisfies Record<
  AppLocale,
  Record<(typeof NAMESPACES)[number], Record<string, unknown>>
>;
`;

const outputs = [
  [resolve("src/shared/i18n/app-messages.ts"), messagesOutput],
  [resolve("src/infrastructure/i18n/resources.ts"), resourcesOutput],
];

if (process.argv.includes("--check")) {
  for (const [target, output] of outputs) {
    let current;

    try {
      current = readFileSync(target, "utf8");
    } catch {
      current = undefined;
    }

    if (current !== output)
      throw new Error("Translation types are stale. Run pnpm i18n:types.");
  }
} else for (const [target, output] of outputs) writeFileSync(target, output);
